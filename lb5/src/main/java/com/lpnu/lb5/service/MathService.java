package com.lpnu.lb5.service;

/**
 * A simple mathematical service for demonstrating unit testing.
 */
public class MathService {

    /**
     * Computes the sum of two integers.
     *
     * @param a first term
     * @param b second term
     * @return sum
     */
    public int sum(int a, int b) {
        return a + b;
    }
}